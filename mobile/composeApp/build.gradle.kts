fun mobileSetting(name: String) = providers.environmentVariable(name).orElse(
    providers.fileContents(rootProject.layout.projectDirectory.file(".env")).asText.map { contents ->
        contents.lineSequence().map { it.trim() }
            .mapNotNull { Regex("(?:export\\s+)?${Regex.escape(name)}\\s*=\\s*(.*)").matchEntire(it)?.groupValues?.get(1) }
            .lastOrNull()?.trim()?.removeSurrounding("\"")?.removeSurrounding("'") ?: ""
    }
)
// Embed only the public origin, never the .env file or server credentials.
val serverOrigin = mobileSetting("THINK_MEET_SERVER_ORIGIN")
val serverConfigDirectory = layout.buildDirectory.dir("generated/serverConfig/commonMain/kotlin")
val generateServerConfig by tasks.registering {
    group = "build setup"
    description = "Read the public HTTPS server origin from the environment or mobile/.env for Android and iOS."
    inputs.property("serverOrigin", serverOrigin.orElse(""))
    outputs.dir(serverConfigDirectory)
    doLast {
        val value = serverOrigin.orNull?.trim().orEmpty()
        val uri = runCatching { URI(value) }.getOrNull()
        require(uri != null && uri.scheme == "https" && !uri.host.isNullOrBlank() &&
            uri.rawUserInfo == null && uri.rawPath in listOf("", "/") &&
            uri.rawQuery == null && uri.rawFragment == null &&
            (uri.port == -1 || uri.port in 1..65535)) {
            "THINK_MEET_SERVER_ORIGIN에 경로 없는 HTTPS 주소를 설정하세요. 환경변수 또는 mobile/.env를 사용합니다."
        }
        val origin = URI("https", null, uri.host.lowercase(), uri.port, null, null, null).toASCIIString()
        val output = serverConfigDirectory.get().file("com/woongjin/thinkmeet/config/ServerConfig.kt").asFile
        output.parentFile.mkdirs()
        output.writeText("""
            |// Generated by generateServerConfig. Do not edit.
            |package com.woongjin.thinkmeet.config
            |
            |object ServerConfig {
            |    const val ORIGIN = "$origin"
            |}
            |
        """.trimMargin())
    }
}
tasks.withType<KotlinCompilationTask<*>>().configureEach { dependsOn(generateServerConfig) }

// Custom development CAs are packaged only in Android debug builds.
val debugServerCa = mobileSetting("THINK_MEET_SERVER_CA_FILE").orElse("").map { path ->
    if (path.isBlank()) layout.projectDirectory.file("src/debug/res/raw/think_meet_root.crt").asFile
    else rootProject.file(path.trim())
}
val debugServerTrustDirectory = layout.buildDirectory.dir("generated/serverTrust/debug/res")
val generateDebugServerTrust by tasks.registering {
    group = "build setup"
    description = "Package the configured public development CA for Android debug builds only."
    inputs.file(debugServerCa)
    val output = debugServerTrustDirectory.map { it.file("raw/think_meet_server_root.crt") }
    outputs.file(output)
    doLast {
        val source = debugServerCa.get()
        require(!source.readText().contains("PRIVATE KEY")) {
            "THINK_MEET_SERVER_CA_FILE에는 개인키 없이 공개 CA 인증서만 지정하세요."
        }
        val certificates = source.inputStream().use { CertificateFactory.getInstance("X.509").generateCertificates(it) }
        require(certificates.isNotEmpty()) { "THINK_MEET_SERVER_CA_FILE에 공개 CA 인증서를 지정하세요." }
        certificates.forEach { certificate ->
            require(certificate is X509Certificate && certificate.basicConstraints >= 0) {
                "THINK_MEET_SERVER_CA_FILE은 서버 인증서가 아닌 공개 CA 인증서여야 합니다."
            }
            certificate.checkValidity()
        }
        val target = output.get().asFile
        target.parentFile.mkdirs()
        source.copyTo(target, overwrite = true)
    }
}

