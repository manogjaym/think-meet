import { createRequire } from 'node:module'
import { createLesson, login, openMaterials } from './helpers'
const require = createRequire(import.meta.url)
const { PDFDocument, rgb } = require('pdf-lib')

const fixtureDirectory=mkdtempSync(join(tmpdir(),'think-meet-e2e-'))
const fixtureVideo=join(fixtureDirectory,'lesson-test.mp4')
test.beforeAll(()=>{
  const flags=['-hide_banner','-loglevel','error','-f','lavfi','-i','testsrc=size=320x180:rate=10','-f','lavfi','-i','sine=frequency=440:sample_rate=44100','-t','8','-c:v','libx264','-pix_fmt','yuv420p','-c:a','aac','-movflags','+faststart','-y']
  if (process.env.THINK_MEET_E2E_HOST_FFMPEG) {
    execFileSync(process.env.THINK_MEET_E2E_HOST_FFMPEG,[...flags,fixtureVideo])
  } else {
    const containerVideo=`/tmp/think-meet-e2e-${randomUUID()}.mp4`
    try {
      execFileSync('docker',['exec','think-meet-api-1','ffmpeg',...flags,containerVideo])
      execFileSync('docker',['cp',`think-meet-api-1:${containerVideo}`,fixtureVideo])
    } finally { execFileSync('docker',['exec','think-meet-api-1','rm','-f',containerVideo]) }
  }
})
test.afterAll(()=>{
  rmSync(fixtureDirectory,{recursive:true,force:true})
})

